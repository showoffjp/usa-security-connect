  platform     text,
  device_id    text,
  created_at   timestamptz NOT NULL DEFAULT now(),
  last_seen_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_device_user ON device_tokens(user_id);

CREATE TABLE IF NOT EXISTS certifications (
  id                integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  user_id           integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  type              text NOT NULL,
  number            text,
  issuing_authority text,
  issued_on         date,
  expires_on        date,
  document_filename text,
  verified_by       integer REFERENCES users(id) ON DELETE SET NULL,
  verified_at       timestamptz,
  notes             text,
  created_at        timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_certs_user ON certifications(user_id);
CREATE INDEX IF NOT EXISTS idx_certs_expiry ON certifications(expires_on);

CREATE TABLE IF NOT EXISTS availability (
  id         integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  user_id    integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  weekday    integer NOT NULL,
  start_time text NOT NULL DEFAULT '00:00',
  end_time   text NOT NULL DEFAULT '23:59',
  available  boolean NOT NULL DEFAULT true,
  note       text,
  UNIQUE (user_id, weekday)
);

CREATE TABLE IF NOT EXISTS time_off_requests (
  id            integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  user_id       integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  type          text NOT NULL DEFAULT 'vacation',
  starts_on     date NOT NULL,
  ends_on       date NOT NULL,
  reason        text,
  status        text NOT NULL DEFAULT 'pending',
  decided_by    integer REFERENCES users(id) ON DELETE SET NULL,
  decided_at    timestamptz,
  decision_note text,
  created_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_timeoff_user ON time_off_requests(user_id, starts_on);
CREATE INDEX IF NOT EXISTS idx_timeoff_status ON time_off_requests(status);

CREATE TABLE IF NOT EXISTS breaks (
  id            integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  time_entry_id integer NOT NULL REFERENCES time_entries(id) ON DELETE CASCADE,
  user_id       integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  type          text NOT NULL DEFAULT 'meal',
  paid          boolean NOT NULL DEFAULT false,
  started_at    timestamptz NOT NULL,
  ended_at      timestamptz,
  minutes       integer,
  start_lat     double precision,
  start_lng     double precision
);
CREATE INDEX IF NOT EXISTS idx_breaks_entry ON breaks(time_entry_id);

CREATE TABLE IF NOT EXISTS panic_alerts (
  id              integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  user_id         integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  time_entry_id   integer REFERENCES time_entries(id) ON DELETE SET NULL,
  post_id         integer REFERENCES posts(id) ON DELETE SET NULL,
  triggered_at    timestamptz NOT NULL DEFAULT now(),
  latitude        double precision,
  longitude       double precision,
  accuracy        double precision,
  note            text,
  status          text NOT NULL DEFAULT 'active',
  acknowledged_by integer REFERENCES users(id) ON DELETE SET NULL,
  acknowledged_at timestamptz,
  resolved_at     timestamptz,
  resolution_note text
);
CREATE INDEX IF NOT EXISTS idx_panic_status ON panic_alerts(status, triggered_at);

-- Officers claiming open shifts, and swapping assigned ones between each other.
CREATE TABLE IF NOT EXISTS shift_requests (
  id             integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  kind           text NOT NULL,                   -- 'claim' | 'swap' | 'drop'
  shift_id       integer NOT NULL REFERENCES shifts(id) ON DELETE CASCADE,
  requested_by   integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  -- For a swap: who is being asked to take it, and what they give back.
  target_user_id integer REFERENCES users(id) ON DELETE CASCADE,
  offered_shift_id integer REFERENCES shifts(id) ON DELETE CASCADE,
  note           text,
  status         text NOT NULL DEFAULT 'pending', -- pending|accepted|declined|approved|denied|cancelled
  decided_by     integer REFERENCES users(id) ON DELETE SET NULL,
  decided_at     timestamptz,
  decision_note  text,
  created_at     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_shift_requests_status ON shift_requests(status, created_at);
CREATE INDEX IF NOT EXISTS idx_shift_requests_shift ON shift_requests(shift_id);

-- Read-only client contacts. Scoped to their own sites, and they never see
-- pay, margin or anything about another client.
CREATE TABLE IF NOT EXISTS client_users (
  id              integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  email           text NOT NULL UNIQUE,
  name            text NOT NULL,
  company         text,
  password_hash   text,
  password_salt   text,
  status          text NOT NULL DEFAULT 'active',
  last_login_at   timestamptz,
  failed_attempts integer NOT NULL DEFAULT 0,
  locked_until    timestamptz,
  created_by      integer REFERENCES users(id) ON DELETE SET NULL,
  created_at      timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS client_sites (
  client_user_id integer NOT NULL REFERENCES client_users(id) ON DELETE CASCADE,
  site_id        integer NOT NULL REFERENCES sites(id) ON DELETE CASCADE,
  PRIMARY KEY (client_user_id, site_id)
);

CREATE TABLE IF NOT EXISTS invoices (
  id            integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  number        text NOT NULL UNIQUE,
  site_id       integer NOT NULL REFERENCES sites(id) ON DELETE RESTRICT,
  period_start  date NOT NULL,
  period_end    date NOT NULL,
  status        text NOT NULL DEFAULT 'draft',   -- draft|sent|paid|void
  subtotal_cents integer NOT NULL DEFAULT 0,
  tax_cents      integer NOT NULL DEFAULT 0,
  total_cents    integer NOT NULL DEFAULT 0,
  -- What the same hours cost us, so margin survives on the record.
  cost_cents     integer NOT NULL DEFAULT 0,
  notes         text,
  issued_at     timestamptz,
  due_on        date,
  paid_at       timestamptz,
  created_by    integer REFERENCES users(id) ON DELETE SET NULL,
  created_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_invoices_site ON invoices(site_id, period_start);

CREATE TABLE IF NOT EXISTS invoice_lines (
  id              integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  invoice_id      integer NOT NULL REFERENCES invoices(id) ON DELETE CASCADE,
  post_id         integer REFERENCES posts(id) ON DELETE SET NULL,
  description     text NOT NULL,
  minutes         integer NOT NULL DEFAULT 0,
  rate_cents      integer NOT NULL DEFAULT 0,
  amount_cents    integer NOT NULL DEFAULT 0,
  cost_cents      integer NOT NULL DEFAULT 0,
  sequence        integer NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_invoice_lines ON invoice_lines(invoice_id, sequence);
